let numeroSolicitado = Number (prompt ("Digite um número:"));
console.log(numeroSolicitado);

let numeroSolicitado2 = Number (prompt ("Digite outro número:"));
console.log(numeroSolicitado2);

let resultado = numeroSolicitado + numeroSolicitado2
alert (`O resultado da soma ${numeroSolicitado} + ${numeroSolicitado2} = ${resultado}`);

let resultado2 = numeroSolicitado - numeroSolicitado2
alert (`O resultado da subtração ${numeroSolicitado} - ${numeroSolicitado2} = ${resultado2}`)

let resultado3 = numeroSolicitado * numeroSolicitado2
alert (`O resultado da multiplicação ${numeroSolicitado} x ${numeroSolicitado2} = ${resultado3}`)

let resultado4 = numeroSolicitado / numeroSolicitado2
alert (`O resultado da divisão é ${numeroSolicitado} / ${numeroSolicitado2} = ${resultado4}`)